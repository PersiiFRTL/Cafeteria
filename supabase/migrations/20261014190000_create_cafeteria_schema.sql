create policy perfiles_select on public.perfiles for select to authenticated
  using (id = (select auth.uid()) or public.tiene_rol(array['ADMINISTRADOR']));
create policy perfiles_admin_insert on public.perfiles for insert to authenticated
  with check (public.tiene_rol(array['ADMINISTRADOR']));
create policy perfiles_admin_update on public.perfiles for update to authenticated
  using (public.tiene_rol(array['ADMINISTRADOR'])) with check (public.tiene_rol(array['ADMINISTRADOR']));
create policy perfiles_admin_delete on public.perfiles for delete to authenticated
  using (public.tiene_rol(array['ADMINISTRADOR']));

