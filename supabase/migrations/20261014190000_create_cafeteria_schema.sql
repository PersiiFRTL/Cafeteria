-- Esquema inicial de Cafeteria.
-- Las políticas requieren Supabase Auth. Un cliente con secret/service_role omite RLS:
-- en ese caso la API del backend debe validar identidad y rol antes de cada operación.

create type public.rol_empleado as enum ('ADMINISTRADOR', 'EMPLEADO', 'COCINA');
create type public.tipo_elaboracion as enum ('bajo_pedido', 'preelaborado', 'reventa');
create type public.unidad_producto as enum ('unidad', 'porcion', 'litro', 'kg');
create type public.unidad_stock as enum ('unidad', 'kg', 'litro');
create type public.tipo_atencion as enum ('mesa', 'take-away');
create type public.estado_comanda as enum ('pendiente', 'preparando', 'lista', 'finalizada', 'cancelada');
create type public.estado_item as enum ('pendiente', 'preparando', 'listo');
create type public.tipo_movimiento as enum ('entrada', 'salida', 'consumo', 'produccion', 'venta', 'merma', 'ajuste');
create type public.tipo_operacion as enum ('produccion', 'comanda', 'entrada', 'salida');
create type public.tipo_elemento_mapa as enum ('mesa', 'linea');

create table public.perfiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nombre text not null check (length(btrim(nombre)) > 0),
  email text unique,
  rol public.rol_empleado not null default 'EMPLEADO',
  activo boolean not null default true,
  creado_en timestamptz not null default now()
);

-- Ignora metadata de rol enviada por el cliente; los usuarios nuevos son EMPLEADO.
create function public.crear_perfil_usuario()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.perfiles (id, nombre, email, rol)
  values (
    new.id,
    coalesce(nullif(btrim(new.raw_user_meta_data ->> 'nombre'), ''),
             nullif(split_part(coalesce(new.email, ''), '@', 1), ''), 'Usuario'),
    new.email,
    'EMPLEADO'
  ) on conflict (id) do nothing;
  return new;
end;
$$;
create trigger al_crear_usuario_auth after insert on auth.users
for each row execute function public.crear_perfil_usuario();

-- SECURITY DEFINER evita recursión al consultar perfiles desde una política RLS.
create function public.tiene_rol(roles_permitidos text[])
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.perfiles p
    where p.id = (select auth.uid())
      and p.activo
      and p.rol::text = any (roles_permitidos)
  );
$$;
revoke all on function public.tiene_rol(text[]) from public, anon;
grant execute on function public.tiene_rol(text[]) to authenticated;
revoke all on function public.crear_perfil_usuario() from public, anon, authenticated;

create table public.mesas (
  id bigint generated by default as identity primary key,
  numero integer not null unique check (numero > 0),
  capacidad integer not null check (capacidad > 0),
  estado text not null default 'libre' check (estado in ('libre', 'ocupada')),
  creado_en timestamptz not null default now()
);

create table public.productos (
  id bigint generated by default as identity primary key,
  nombre text not null check (length(btrim(nombre)) > 0),
  precio numeric(12,2) not null default 0 check (precio >= 0),
  categoria text not null,
  sector text not null check (sector in ('Cocina', 'Cafetería', 'Pastelería')),
  tipo_elaboracion public.tipo_elaboracion not null,
  unidad_venta public.unidad_producto not null default 'unidad',
  stock_actual numeric(12,3) not null default 0 check (stock_actual >= 0),
  stock_minimo numeric(12,3) not null default 0 check (stock_minimo >= 0),
  activo boolean not null default true,
  disponible boolean not null default true,
  creado_en timestamptz not null default now()
);

create table public.materias_primas (
  id bigint generated by default as identity primary key,
  nombre text not null check (length(btrim(nombre)) > 0),
  categoria text not null,
  unidad public.unidad_stock not null,
  stock_actual numeric(12,3) not null default 0 check (stock_actual >= 0),
  stock_minimo numeric(12,3) not null default 0 check (stock_minimo >= 0),
  activo boolean not null default true,
  creado_en timestamptz not null default now()
);

create table public.recetas (
  id bigint generated by default as identity primary key,
  producto_id bigint not null unique references public.productos(id) on delete cascade,
  creado_en timestamptz not null default now()
);
create table public.receta_ingredientes (
  receta_id bigint not null references public.recetas(id) on delete cascade,
  materia_prima_id bigint not null references public.materias_primas(id) on delete restrict,
  cantidad numeric(12,3) not null check (cantidad > 0),
  primary key (receta_id, materia_prima_id)
);

create table public.comandas (
  id bigint generated by default as identity primary key,
  tipo_atencion public.tipo_atencion not null,
  mesa_id bigint references public.mesas(id) on delete restrict,
  cliente_nombre text,
  cliente_telefono text,
  hora_retiro timestamptz,
  estado public.estado_comanda not null default 'pendiente',
  creada_por uuid references public.perfiles(id) on delete set null,
  fecha_creacion timestamptz not null default now(),
  inicio_preparacion timestamptz,
  fecha_lista timestamptz,
  fecha_finalizacion timestamptz,
  fecha_cancelacion timestamptz,
  constraint datos_atencion_validos check (
    (tipo_atencion = 'mesa' and mesa_id is not null and cliente_nombre is null
      and cliente_telefono is null and hora_retiro is null)
    or
    (tipo_atencion = 'take-away' and mesa_id is null
      and cliente_nombre is not null and length(btrim(cliente_nombre)) > 0
      and hora_retiro is not null)
  )
);
create unique index comandas_una_activa_por_mesa on public.comandas (mesa_id)
  where mesa_id is not null and estado in ('pendiente', 'preparando', 'lista');
create index comandas_estado_fecha_idx on public.comandas (estado, fecha_creacion desc);

create table public.comanda_items (
  id bigint generated by default as identity primary key,
  comanda_id bigint not null references public.comandas(id) on delete cascade,
  producto_id bigint not null references public.productos(id) on delete restrict,
  nombre_producto text not null,
  precio_unitario numeric(12,2) not null check (precio_unitario >= 0),
  cantidad numeric(12,3) not null check (cantidad > 0),
  estado public.estado_item not null default 'pendiente',
  cantidad_stock_procesada numeric(12,3) not null default 0
    check (cantidad_stock_procesada >= 0 and cantidad_stock_procesada <= cantidad),
  creado_en timestamptz not null default now()
);
create index comanda_items_comanda_idx on public.comanda_items (comanda_id);

create table public.producciones (
  id bigint generated by default as identity primary key,
  producto_id bigint not null references public.productos(id) on delete restrict,
  cantidad numeric(12,3) not null check (cantidad > 0),
  fecha timestamptz not null default now(),
  creada_por uuid references public.perfiles(id) on delete set null
);

create table public.operaciones_stock (
  id bigint generated by default as identity primary key,
  tipo public.tipo_operacion not null,
  comanda_id bigint references public.comandas(id) on delete restrict,
  produccion_id bigint references public.producciones(id) on delete restrict,
  fecha timestamptz not null default now(),
  descripcion text not null default '',
  creada_por uuid references public.perfiles(id) on delete set null,
  constraint referencia_operacion_valida check (
    (tipo = 'comanda' and comanda_id is not null and produccion_id is null)
    or (tipo = 'produccion' and produccion_id is not null and comanda_id is null)
    or (tipo in ('entrada', 'salida') and comanda_id is null and produccion_id is null)
  )
);
create table public.movimientos_stock (
  id bigint generated by default as identity primary key,
  operacion_id bigint not null references public.operaciones_stock(id) on delete restrict,
  tipo public.tipo_movimiento not null,
  materia_prima_id bigint references public.materias_primas(id) on delete restrict,
  producto_id bigint references public.productos(id) on delete restrict,
  cantidad numeric(12,3) not null check (cantidad > 0),
  fecha timestamptz not null default now(),
  descripcion text not null default '',
  constraint un_solo_articulo_stock check (num_nonnulls(materia_prima_id, producto_id) = 1)
);
create index movimientos_stock_operacion_idx on public.movimientos_stock (operacion_id);
create index movimientos_stock_fecha_idx on public.movimientos_stock (fecha desc);

create table public.elementos_mapa (
  id text primary key,
  tipo public.tipo_elemento_mapa not null,
  x numeric(10,2) not null,
  y numeric(10,2) not null,
  ancho numeric(10,2) not null check (ancho > 0),
  alto numeric(10,2) not null check (alto > 0),
  rotacion numeric(7,2) not null default 0,
  mesa_id bigint references public.mesas(id) on delete cascade,
  grosor numeric(10,2) check (grosor is null or grosor > 0),
  constraint datos_elemento_mapa_validos check (
    (tipo = 'mesa' and mesa_id is not null and grosor is null)
    or (tipo = 'linea' and mesa_id is null)
  )
);
create unique index elementos_mapa_una_posicion_por_mesa on public.elementos_mapa (mesa_id)
  where mesa_id is not null;

