create table public.auditoria_eventos (
  id bigint generated by default as identity primary key,
  usuario_id uuid references public.perfiles(id) on delete set null,
  usuario_nombre text not null,
  entidad text not null,
  entidad_id text not null,
  accion text not null,
  detalle text not null,
  fecha timestamptz not null default now()
);

create index auditoria_eventos_fecha_idx
  on public.auditoria_eventos (fecha desc);
create index auditoria_eventos_entidad_idx
  on public.auditoria_eventos (entidad, entidad_id, fecha desc);

alter table public.auditoria_eventos enable row level security;
revoke all on public.auditoria_eventos from public, anon, authenticated;
grant select on public.auditoria_eventos to authenticated;

create policy auditoria_eventos_admin_read
  on public.auditoria_eventos for select to authenticated
  using (public.tiene_rol(array['ADMINISTRADOR']));

create or replace function public.registrar_evento_auditoria()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_anterior jsonb;
  v_nuevo jsonb;
  v_usuario_id uuid := auth.uid();
  v_usuario_nombre text;
  v_entidad text := tg_table_name;
  v_entidad_id text;
  v_accion text;
  v_detalle text;
  v_estado_anterior text;
  v_estado_nuevo text;
begin
  if tg_op <> 'INSERT' then
    v_anterior := to_jsonb(old);
  end if;
  if tg_op <> 'DELETE' then
    v_nuevo := to_jsonb(new);
  end if;

  if tg_table_name = 'comandas' then
    v_entidad := 'comanda';
    v_entidad_id := coalesce(v_nuevo ->> 'id', v_anterior ->> 'id');
    if tg_op = 'INSERT' then
      v_usuario_id := coalesce(v_usuario_id, nullif(v_nuevo ->> 'creada_por', '')::uuid);
      v_accion := 'Creó comanda';
      v_detalle := 'Creó la comanda #' || v_entidad_id;
    elsif tg_op = 'DELETE' then
      v_accion := 'Eliminó comanda';
      v_detalle := 'Eliminó la comanda #' || v_entidad_id;
    elsif v_anterior ->> 'estado' is distinct from v_nuevo ->> 'estado' then
      v_estado_anterior := case v_anterior ->> 'estado'
        when 'pendiente' then 'Pendiente'
        when 'preparando' then 'En preparación'
        when 'lista' then 'Lista'
        when 'finalizada' then 'Entregada'
        when 'cancelada' then 'Cancelada'
        else v_anterior ->> 'estado'
      end;
      v_estado_nuevo := case v_nuevo ->> 'estado'
        when 'pendiente' then 'Pendiente'
        when 'preparando' then 'En preparación'
        when 'lista' then 'Lista'
        when 'finalizada' then 'Entregada'
        when 'cancelada' then 'Cancelada'
        else v_nuevo ->> 'estado'
      end;
      v_accion := 'Cambió estado de comanda';
      v_detalle := 'Comanda #' || v_entidad_id || ': ' || v_estado_anterior || ' → ' || v_estado_nuevo;
    elsif v_anterior is distinct from v_nuevo then
      v_accion := 'Editó comanda';
      v_detalle := 'Modificó la comanda #' || v_entidad_id;
    else
      return new;
    end if;

  elsif tg_table_name = 'comanda_items' then
    v_entidad := 'comanda';
    v_entidad_id := coalesce(v_nuevo ->> 'comanda_id', v_anterior ->> 'comanda_id');
    if tg_op = 'INSERT' then
      v_accion := 'Agregó producto a comanda';
      v_detalle := 'Agregó ' || coalesce(v_nuevo ->> 'cantidad', '1') || ' × ' ||
        coalesce(v_nuevo ->> 'nombre_producto', 'producto') || ' a la comanda #' || v_entidad_id;
    elsif tg_op = 'DELETE' then
      v_accion := 'Quitó producto de comanda';
      v_detalle := 'Quitó ' || coalesce(v_anterior ->> 'nombre_producto', 'producto') ||
        ' de la comanda #' || v_entidad_id;
    elsif v_anterior ->> 'estado' is distinct from v_nuevo ->> 'estado' then
      v_accion := 'Cambió preparación de producto';
      v_detalle := coalesce(v_nuevo ->> 'nombre_producto', 'Producto') || ' en comanda #' || v_entidad_id ||
        ': ' || (v_anterior ->> 'estado') || ' → ' || (v_nuevo ->> 'estado');
    elsif v_anterior ->> 'cantidad' is distinct from v_nuevo ->> 'cantidad'
       or v_anterior ->> 'producto_id' is distinct from v_nuevo ->> 'producto_id' then
      v_accion := 'Editó productos de comanda';
      v_detalle := 'Modificó ' || coalesce(v_nuevo ->> 'nombre_producto', v_anterior ->> 'nombre_producto', 'un producto') ||
        ' en la comanda #' || v_entidad_id;
    else
      return new;
    end if;

  elsif tg_table_name = 'productos' then
    v_entidad := 'producto';
    v_entidad_id := coalesce(v_nuevo ->> 'id', v_anterior ->> 'id');
    if tg_op = 'INSERT' then
      v_accion := 'Creó producto';
      v_detalle := 'Creó el producto ' || coalesce(v_nuevo ->> 'nombre', '#' || v_entidad_id);
    elsif tg_op = 'DELETE' then
      v_accion := 'Eliminó producto';
      v_detalle := 'Eliminó el producto ' || coalesce(v_anterior ->> 'nombre', '#' || v_entidad_id);
    elsif v_anterior ->> 'activo' is distinct from v_nuevo ->> 'activo' then
      v_accion := case when (v_nuevo ->> 'activo')::boolean then 'Activó producto' else 'Desactivó producto' end;
      v_detalle := v_accion || ': ' || coalesce(v_nuevo ->> 'nombre', '#' || v_entidad_id);
    elsif v_anterior is distinct from v_nuevo then
      v_accion := 'Editó producto';
      v_detalle := 'Editó el producto ' || coalesce(v_nuevo ->> 'nombre', '#' || v_entidad_id);
    else
      return new;
    end if;

  elsif tg_table_name = 'materias_primas' then
    v_entidad := 'materia prima';
    v_entidad_id := coalesce(v_nuevo ->> 'id', v_anterior ->> 'id');
    if tg_op = 'INSERT' then
      v_accion := 'Creó materia prima';
      v_detalle := 'Creó la materia prima ' || coalesce(v_nuevo ->> 'nombre', '#' || v_entidad_id);
    elsif tg_op = 'DELETE' then
      v_accion := 'Eliminó materia prima';
      v_detalle := 'Eliminó la materia prima ' || coalesce(v_anterior ->> 'nombre', '#' || v_entidad_id);
    elsif v_anterior ->> 'activo' is distinct from v_nuevo ->> 'activo' then
      v_accion := case when (v_nuevo ->> 'activo')::boolean then 'Activó materia prima' else 'Desactivó materia prima' end;
      v_detalle := v_accion || ': ' || coalesce(v_nuevo ->> 'nombre', '#' || v_entidad_id);
    elsif v_anterior is distinct from v_nuevo then
      v_accion := 'Editó materia prima';
      v_detalle := 'Editó la materia prima ' || coalesce(v_nuevo ->> 'nombre', '#' || v_entidad_id);
    else
      return new;
    end if;

  elsif tg_table_name = 'perfiles' then
    v_entidad := 'empleado';
    v_entidad_id := coalesce(v_nuevo ->> 'id', v_anterior ->> 'id');
    if tg_op = 'INSERT' then
      v_accion := 'Creó empleado';
      v_detalle := 'Creó el perfil ' || coalesce(v_nuevo ->> 'nombre', '#' || v_entidad_id);
    elsif tg_op = 'DELETE' then
      v_accion := 'Eliminó empleado';
      v_detalle := 'Eliminó el perfil ' || coalesce(v_anterior ->> 'nombre', '#' || v_entidad_id);
    elsif v_anterior ->> 'activo' is distinct from v_nuevo ->> 'activo' then
      v_accion := case when (v_nuevo ->> 'activo')::boolean then 'Activó empleado' else 'Desactivó empleado' end;
      v_detalle := v_accion || ': ' || coalesce(v_nuevo ->> 'nombre', '#' || v_entidad_id);
    elsif v_anterior ->> 'rol' is distinct from v_nuevo ->> 'rol' then
      v_accion := 'Cambió rol de empleado';
      v_detalle := coalesce(v_nuevo ->> 'nombre', '#' || v_entidad_id) || ': ' ||
        (v_anterior ->> 'rol') || ' → ' || (v_nuevo ->> 'rol');
    elsif v_anterior is distinct from v_nuevo then
      v_accion := 'Editó empleado';
      v_detalle := 'Editó el perfil ' || coalesce(v_nuevo ->> 'nombre', '#' || v_entidad_id);
    else
      -- La ruta de alta sincroniza el perfil con Auth mediante UPDATE,
      -- incluso cuando el perfil ya coincide con los datos enviados.
      v_accion := 'Gestionó perfil de empleado';
      v_detalle := 'Gestionó el perfil ' || coalesce(v_nuevo ->> 'nombre', '#' || v_entidad_id);
    end if;

  elsif tg_table_name = 'recetas' then
    v_entidad := 'receta';
    v_entidad_id := coalesce(v_nuevo ->> 'id', v_anterior ->> 'id');
    if tg_op = 'INSERT' then
      v_accion := 'Creó receta';
      v_detalle := 'Creó la receta del producto #' || coalesce(v_nuevo ->> 'producto_id', 'desconocido');
    elsif tg_op = 'DELETE' then
      v_accion := 'Eliminó receta';
      v_detalle := 'Eliminó la receta del producto #' || coalesce(v_anterior ->> 'producto_id', 'desconocido');
    else
      -- guardar_receta hace un UPSERT sobre la fila aun cuando solo cambian los ingredientes.
      v_accion := 'Editó receta';
      v_detalle := 'Actualizó la receta del producto #' || coalesce(v_nuevo ->> 'producto_id', 'desconocido');
    end if;

  elsif tg_table_name = 'operaciones_stock' then
    v_usuario_id := coalesce(v_usuario_id, nullif(v_nuevo ->> 'creada_por', '')::uuid);
    v_entidad := 'stock';
    v_entidad_id := v_nuevo ->> 'id';
    v_accion := 'Registró operación de stock';
    v_detalle := coalesce(v_nuevo ->> 'descripcion', 'Registró un movimiento de stock');
  else
    if tg_op = 'DELETE' then
      return old;
    end if;
    return new;
  end if;

  if v_usuario_id is null then
    if tg_op = 'DELETE' then
      return old;
    end if;
    return new;
  end if;

  select p.nombre into v_usuario_nombre
  from public.perfiles p
  where p.id = v_usuario_id;

  insert into public.auditoria_eventos
    (usuario_id, usuario_nombre, entidad, entidad_id, accion, detalle)
  values (
    v_usuario_id,
    coalesce(v_usuario_nombre, 'Usuario'),
    v_entidad,
    coalesce(v_entidad_id, 'sin-id'),
    v_accion,
    v_detalle
  );

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

revoke all on function public.registrar_evento_auditoria() from public, anon, authenticated;

create trigger auditoria_comandas
  after insert or update or delete on public.comandas
  for each row execute function public.registrar_evento_auditoria();
create trigger auditoria_comanda_items
  after insert or update or delete on public.comanda_items
  for each row execute function public.registrar_evento_auditoria();
create trigger auditoria_productos
  after insert or update or delete on public.productos
  for each row execute function public.registrar_evento_auditoria();
create trigger auditoria_materias_primas
  after insert or update or delete on public.materias_primas
  for each row execute function public.registrar_evento_auditoria();
create trigger auditoria_perfiles
  after insert or update or delete on public.perfiles
  for each row execute function public.registrar_evento_auditoria();
create trigger auditoria_recetas
  after insert or update or delete on public.recetas
  for each row execute function public.registrar_evento_auditoria();
create trigger auditoria_operaciones_stock
  after insert on public.operaciones_stock
  for each row execute function public.registrar_evento_auditoria();
